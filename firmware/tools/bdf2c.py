#!/usr/bin/env python3
"""Convert Spleen BDF fonts to the C tables in main/font.c (printable ASCII plus the degree sign).

Usage: tools/bdf2c.py spleen-16x32.bdf spleen-32x64.bdf > main/font.c
Spleen: https://github.com/fcambus/spleen (BSD-2-Clause, see notice in the generated file).
"""
import sys

FIRST, LAST = 32, 126
EXTRA = [176]  # degree sign, stored right after '~' (glyph index 95); gfx.c maps U+00B0 to it


def parse(path):
    w = h = None
    glyphs, enc, bits, in_bitmap = {}, None, [], False
    for line in open(path, encoding="latin-1"):
        tok = line.split()
        if not tok:
            continue
        if tok[0] == "FONTBOUNDINGBOX":
            w, h = int(tok[1]), int(tok[2])
        elif tok[0] == "ENCODING":
            enc = int(tok[1])
        elif tok[0] == "BBX":
            # The renderer assumes every glyph fills the whole cell; Spleen does.
            assert (int(tok[1]), int(tok[2])) == (w, h), f"{path}: glyph {enc} is not full-cell"
        elif tok[0] == "BITMAP":
            in_bitmap, bits = True, []
        elif tok[0] == "ENDCHAR":
            in_bitmap = False
            if FIRST <= enc <= LAST or enc in EXTRA:
                glyphs[enc] = bits
        elif in_bitmap:
            bits.append(tok[0])
    missing = [c for c in list(range(FIRST, LAST + 1)) + EXTRA if c not in glyphs]
    assert not missing, f"{path}: missing glyphs {missing}"
    return w, h, glyphs


def main():
    print("// Generated by tools/bdf2c.py from Spleen 2.1.0. Do not edit.")
    print("//")
    print("// Spleen: Copyright (c) 2018-2024, Frederic Cambus. All rights reserved.")
    print("// Redistribution and use in source and binary forms, with or without modification, are permitted")
    print("// provided that the following conditions are met: (1) redistributions of source code must retain the")
    print("// above copyright notice, this list of conditions and the following disclaimer; (2) redistributions in")
    print("// binary form must reproduce the above copyright notice, this list of conditions and the following")
    print("// disclaimer in the documentation and/or other materials provided with the distribution.")
    print("// THIS SOFTWARE IS PROVIDED BY THE COPYRIGHT HOLDERS AND CONTRIBUTORS \"AS IS\" AND ANY EXPRESS OR IMPLIED")
    print("// WARRANTIES ARE DISCLAIMED.")
    print('#include "font.h"\n')
    for path in sys.argv[1:]:
        w, h, glyphs = parse(path)
        name = f"font_{w}x{h}"
        print(f"static const uint8_t {name}_bits[] = {{")
        for c in list(range(FIRST, LAST + 1)) + EXTRA:
            data = bytes.fromhex("".join(glyphs[c]))
            assert len(data) == w // 8 * h
            print("    " + ",".join(f"0x{b:02x}" for b in data) + f", // U+{c:04X}")
        print("};")
        print(f"const font_t {name} = {{{w}, {h}, {name}_bits}};\n")


main()
