#!/usr/bin/env python3
"""Generates main/tzdb.c: IANA zone name -> POSIX TZ string, so the frame can use the zone an IP lookup
returns (e.g. America/Chicago). Source: posix_tz_db zones.json (MIT, github.com/nayarsystems/posix_tz_db).

Usage: tools/tzdb2c.py zones.json > main/tzdb.c
"""
import json, sys

zones = sorted(json.load(open(sys.argv[1])).items())
print("// Generated by tools/tzdb2c.py from posix_tz_db (MIT, github.com/nayarsystems/posix_tz_db). Do not edit.")
print('#include "tzdb.h"\n#include <stddef.h>\n#include <string.h>\n')
print("static const struct { const char *iana, *posix; } ZONES[] = {  // sorted by name")
for k, v in zones:
    print(f'    {{"{k}", "{v}"}},')
print("};\n")
print("""const char *tzdb_posix(const char *iana) {
    size_t lo = 0, hi = sizeof(ZONES) / sizeof(ZONES[0]);
    while (lo < hi) {
        size_t mid = (lo + hi) / 2;
        int c = strcmp(iana, ZONES[mid].iana);
        if (!c) return ZONES[mid].posix;
        if (c < 0) hi = mid;
        else lo = mid + 1;
    }
    return NULL;
}""")
